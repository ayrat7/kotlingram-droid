val DEFAULT_COUNTRY: Country = COUNTRIES.first()

/** Страна по ISO-коду (RU, US…) или null. */
fun countryByIso(iso: String): Country? = COUNTRIES.firstOrNull { it.iso.equals(iso, ignoreCase = true) }

/** Подбирает страну по введённым цифрам (с кодом в начале): сначала длинные коды. */
fun matchCountry(digits: String): Country? {
    for (len in minOf(3, digits.length) downTo 1) {
        val c = COUNTRIES.firstOrNull { it.code == digits.take(len) }
        if (c != null) return c
    }
    return null
}
